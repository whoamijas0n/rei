def resolve_icon_name(icon_name: str) -> str:
    """Resuelve un nombre o alias de icono a su clave canónica registrada."""
    token = (icon_name or "").upper().strip()
    if token in _ICON_SPRITES:
        return token
    canonical = _ICON_ALIASES.get(token)
    if canonical and canonical in _ICON_SPRITES:
        return canonical
    return "DEFAULT"


@lru_cache(maxsize=64)
def get_icon_bitmap(canonical_name: str) -> Image.Image:
    """Compila y cachea una matriz ASCII 20x20 en un objeto PIL Image modo '1'."""
    grid = _ICON_SPRITES.get(canonical_name, _ICON_SPRITES["DEFAULT"])
    img = Image.new("1", (ICON_SIZE, ICON_SIZE), 0)
    pixels = img.load()
    for y, row in enumerate(grid[:ICON_SIZE]):
        for x, ch in enumerate(row[:ICON_SIZE]):
            if ch == "#":
                pixels[x, y] = 1
    return img


class IconRenderer:
    """
    Motor de iconos pixel-art 20x20 de trazo fino para la pantalla OLED SH1106.
    Renderiza sprites monocromáticos cacheados centrados en (cx, cy).
    """

    @classmethod
    def list_icons(cls) -> List[str]:
        """Devuelve la lista ordenada de todos los nombres y alias válidos."""
        return sorted(set(_ICON_SPRITES.keys()) | set(_ICON_ALIASES.keys()))

    @classmethod
    def draw_icon(
        cls,
        draw: ImageDraw.ImageDraw,
        icon_name: str,
        cx: int = 64,
        cy: int = 24,
        center_x: Optional[int] = None,
        center_y: Optional[int] = None,
        fill: str = "white",
    ) -> None:
        """Dibuja el icono solicitado centrado en (cx, cy) sobre el canvas PIL."""
        if center_x is not None:
            cx = center_x
        if center_y is not None:
            cy = center_y
        canonical = resolve_icon_name(icon_name)
        bitmap = get_icon_bitmap(canonical)
        top_left = (cx - ICON_SIZE // 2, cy - ICON_SIZE // 2)
        draw.bitmap(top_left, bitmap, fill=fill)
