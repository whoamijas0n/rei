from PIL import Image

def _str_to_image(icon_str: str) -> Image.Image:
    lines = icon_str.strip().split('\n')
    img = Image.new('1', (20, 20), color=0)
    pixels = img.load()
    for y, line in enumerate(lines):
        for x, char in enumerate(line):
            if char == '#' and x < 20 and y < 20:
                pixels[x, y] = 1
    return img

